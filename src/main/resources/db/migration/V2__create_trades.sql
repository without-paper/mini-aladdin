
CREATE TABLE trades (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    portfolio_id BIGINT NOT NULL,

    symbol VARCHAR(20) NOT NULL,

    side VARCHAR(4) NOT NULL,

    quantity NUMERIC(19, 0) NOT NULL,

    price NUMERIC(19, 2) NOT NULL,

    executed_at TIMESTAMP WITH TIME ZONE NOT NULL,

    CONSTRAINT fk_trade_portfolio
        FOREIGN KEY (portfolio_id)
        REFERENCES portfolios(id),

    CONSTRAINT chk_trade_side
        CHECK (side IN ('BUY', 'SELL')),

    CONSTRAINT chk_trade_quantity
        CHECK (quantity > 0),

    CONSTRAINT chk_trade_price
        CHECK (price > 0)
);

CREATE INDEX idx_trades_portfolio_id
    ON trades(portfolio_id);

CREATE INDEX idx_trades_portfolio_symbol
    ON trades(portfolio_id, symbol);
